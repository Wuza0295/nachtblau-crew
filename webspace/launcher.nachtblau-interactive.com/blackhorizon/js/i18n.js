    _pack(lang) {
      if (lang === "de") return DE;
      const en = EN;
      const over = (this.packs[lang] || {});
      return Object.assign({}, DE, en, over);
    },

    getLang() {
      const s = BH.Progress && BH.Progress.data && BH.Progress.data.settings;
      const id = (s && s.language) || this.defaultLang;
      return this.packs[id] || id === "de" || id === "en" ? id : this.defaultLang;
    },

    locale() {
      const lang = this.langs.find(l => l.id === this.getLang());
      return lang ? lang.locale : "de-DE";
    },

    fmt(n) {
      const num = Number(n) || 0;
      try { return num.toLocaleString(this.locale()); } catch (e) { return String(num); }
    },

    t(key, params) {
      const pack = this._pack(this.getLang());
      let text = pack[key] || EN[key] || DE[key] || key;
      if (params) {
        for (const k of Object.keys(params)) {
          text = text.replace(new RegExp("\\{" + k + "\\}", "g"), params[k]);
        }
      }
      return text;
    },

    modeName(id) {
      const key = MODE_KEYS[id];
      return key ? this.t(key) : id;
    },

    setLang(id) {
      if (!this.packs[id] && id !== "de" && id !== "en") return false;
      if (!BH.Progress.data.settings) BH.Progress.data.settings = {};
      BH.Progress.data.settings.language = id;
      BH.Progress.save();
      document.documentElement.lang = id;
      this.apply();
      return true;
    },

