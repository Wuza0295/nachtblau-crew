function resolveGlyph(ch) {
  if (GLYPHS[ch]) return GLYPHS[ch];
  const up = ch.toUpperCase();
  if (GLYPHS[up]) return GLYPHS[up];
  return GLYPHS['?'];
}

export function measureText(text, scale = 1) {
  const advance = (COLS + 1) * scale;
  return String(text ?? '').length * advance;
}

/**
 * Draw crisp pixel text.
 * @param {CanvasRenderingContext2D} ctx
 * @param {string} text
 * @param {number} x
 * @param {number} y baseline-ish top-left of glyph row
 * @param {object} [opts]
 */
export function drawText(ctx, text, x, y, opts = {}) {
  const {
    color = '#f8f0d0',
    shadow = '#080610',
    scale = 1,
    align = 'left',
  } = opts;

  const str = String(text ?? '');
  const advance = (COLS + 1) * scale;
  const width = str.length * advance;
  let cx = Math.floor(x);
  if (align === 'center') cx = Math.floor(x - width / 2);
  else if (align === 'right') cx = Math.floor(x - width);

  const cy = Math.floor(y);

  for (let i = 0; i < str.length; i++) {
    const glyph = resolveGlyph(str[i]);
    const gx = cx + i * advance;
    if (shadow) {
      for (let row = 0; row < ROWS; row++) {
        const line = glyph[row];
        for (let col = 0; col < COLS; col++) {
          if (line[col] === '#') {
            ctx.fillStyle = shadow;
            ctx.fillRect(gx + col * scale + scale, cy + row * scale + scale, scale, scale);
          }
        }
      }
    }
    ctx.fillStyle = color;
    for (let row = 0; row < ROWS; row++) {
      const line = glyph[row];
      for (let col = 0; col < COLS; col++) {
        if (line[col] === '#') {
          ctx.fillRect(gx + col * scale, cy + row * scale, scale, scale);
        }
      }
    }
  }

  return width;
}

export function drawTextLines(ctx, lines, x, y, opts = {}) {
  const scale = opts.scale ?? 1;
  const lineH = (ROWS + 2) * scale;
  lines.forEach((line, i) => {
    drawText(ctx, line, x, y + i * lineH, opts);
  });
}

